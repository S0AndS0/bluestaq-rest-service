DROP DATABASE IF EXISTS user_accounts WITH (FORCE);
CREATE DATABASE user_accounts;

\c user_accounts

/**
 * - `id` is shared between all `account_` prefixed tables
 * - `date_created` is when account was first created
 * - `date_emailed` is last time "magic link" was sent
 * - `date_logged_in` is last time "magic link" was successfully used
 * - `email_normalized` is data parsed from user, do NOT trust it!!!
 * - `email_raw` is data parsed from user, do NOT trust it!!!
 * - `notes` is simple dictionary of key -> relative upload path, and value -> save date/time
 *
 * API should use `date_emailed` to prevent emailing "magic link" multiple
 * times too quickly.
 *
 * API should use `date_logged_in` and `date_created` to detect accounts that
 * have never been used, after some number of days/weeks/months.
 */
CREATE TABLE IF NOT EXISTS account_data (
  id                  bigint PRIMARY KEY generated by DEFAULT as identity,
  date_created        timestamptz DEFAULT NOW(),
  date_emailed        timestamptz DEFAULT NOW(),
  date_logged_in      timestamptz DEFAULT NOW(),
  email_normalized    VARCHAR(254) UNIQUE,
  email_raw           VARCHAR(254) NOT NULL,
  notes               jsonb DEFAULT '{}'::jsonb
);

